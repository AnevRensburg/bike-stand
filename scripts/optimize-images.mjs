#!/usr/bin/env node
/**
 * Image pipeline: converts the original photos in images-src/ into AVIF + WebP at a few widths,
 * writes them to public/images, and generates a typed manifest that <app-picture> reads
 * (intrinsic size + available widths). Also builds the social preview image and favicons.
 *
 * To swap a photo: drop the new original into images-src/ under the same name (any of
 * .jpg/.jpeg/.png/.webp), or change the file name in `jobs` below, then run `npm run images`.
 *
 * sharp is a devDependency only; the committed output in public/images is what ships.
 */
import { access, mkdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'images-src');
const outDir = path.join(root, 'public/images');
const manifestFile = path.join(root, 'src/app/data/image-manifest.ts');

/** Groups: output folder, [source base name (no extension), output name], target widths, quality. */
const jobs = [
  {
    dir: 'product',
    items: [
      ['stand-bike', 'stand-bike'],
      ['stand', 'stand'],
    ],
    widths: [480, 960, 1500],
    avif: 55,
    webp: 78,
  },
];

const EXTENSIONS = ['.jpg', '.jpeg', '.png', '.webp', '.JPG', '.JPEG', '.PNG'];

async function findSource(base) {
  for (const ext of EXTENSIONS) {
    const file = path.join(source, base + ext);
    try {
      await access(file);
      return file;
    } catch {}
  }
  throw new Error(`Missing original: images-src/${base}.(jpg|png|webp)`);
}

const fmtKB = (bytes) => `${(bytes / 1024).toFixed(0)} kB`;
const fmtMB = (bytes) => `${(bytes / 1024 / 1024).toFixed(2)} MB`;

let before = 0;
let after = 0;
const manifest = {};

async function writeTracked(pipeline, file) {
  const info = await pipeline.toFile(file);
  after += info.size;
  return info;
}

await rm(outDir, { recursive: true, force: true });

for (const job of jobs) {
  await mkdir(path.join(outDir, job.dir), { recursive: true });
  for (const [base, name] of job.items) {
    const input = await findSource(base);
    before += (await stat(input)).size;
    // Width after EXIF rotation, so portrait phone photos are measured the right way round.
    const { info: oriented } = await sharp(input).rotate().toBuffer({ resolveWithObject: true });
    const widths = [...new Set(job.widths.map((w) => Math.min(w, oriented.width)))].sort(
      (a, b) => a - b,
    );
    let maxHeight = 0;
    for (const width of widths) {
      const base = sharp(input).rotate().resize({ width, withoutEnlargement: true });
      const out = path.join(outDir, job.dir, `${name}-${width}`);
      const info = await writeTracked(
        base.clone().avif({ quality: job.avif, effort: 6 }),
        `${out}.avif`,
      );
      await writeTracked(base.clone().webp({ quality: job.webp, effort: 6 }), `${out}.webp`);
      maxHeight = info.height;
    }
    const key = `${job.dir}/${name}`;
    manifest[key] = { width: widths.at(-1), height: maxHeight, widths };
    console.log(`${path.basename(input).padEnd(24)} -> ${key} [${widths.join(', ')}]`);
  }
}

// Open Graph / social preview: 1200x630 JPEG (AVIF/WebP are not reliably supported by crawlers).
await writeTracked(
  sharp(await findSource('stand-bike'))
    .rotate()
    .resize({ width: 1200, height: 630, fit: 'contain', background: '#ffffff' })
    .jpeg({ quality: 78, mozjpeg: true }),
  path.join(outDir, 'og-image.jpg'),
);

// Favicons: the stand photo, padded to a square on white.
const stand = await findSource('stand');
const square = (size) =>
  sharp(stand)
    .rotate()
    .resize({ width: size, height: size, fit: 'contain', background: '#ffffff' })
    .flatten({ background: '#ffffff' })
    .png({ compressionLevel: 9 });
await writeTracked(square(48), path.join(root, 'public/favicon.png'));
await writeTracked(square(180), path.join(root, 'public/apple-touch-icon.png'));

await writeFile(
  manifestFile,
  `// Generated by scripts/optimize-images.mjs. Do not edit by hand.\n\n` +
    `export interface ImageEntry {\n  /** Intrinsic width of the largest generated file. */\n  readonly width: number;\n  readonly height: number;\n  /** Widths generated as <name>-<width>.avif / .webp. */\n  readonly widths: readonly number[];\n}\n\n` +
    `export const IMAGE_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, ImageEntry>;\n\n` +
    `export type ImageKey = keyof typeof IMAGE_MANIFEST;\n`,
);

console.log(
  `\nOriginals used: ${fmtMB(before)}  ->  optimised output: ${fmtMB(after)} (${fmtKB(after)})`,
);
console.log(`Reduction: ${(100 - (after / before) * 100).toFixed(1)}%`);
